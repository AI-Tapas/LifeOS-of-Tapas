// Generate metadata without importing server-only modules or requiring secrets.
// Evaluate only named, pure metadata declarations in a sandbox. Any new runtime
// dependency fails generation instead of calling production services.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import * as tools from "../lib/assistant/tools.ts";
import { ALL_CAPABILITIES, CAPABILITY_DESCRIPTIONS, capabilityAllows } from "../lib/mcp/permissions.ts";
import { listResources, listPrompts } from "../lib/mcp/catalog.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
function metadata(file, names, bindings) {
  const source = ts.createSourceFile(file, fs.readFileSync(path.join(root, file), "utf8"), ts.ScriptTarget.Latest, true);
  const statements = source.statements.filter(node =>
    ts.isVariableStatement(node) ? node.declarationList.declarations.some(d => names.includes(d.name.getText(source))) : ts.isFunctionDeclaration(node) && names.includes(node.name?.text));
  const code = ts.createPrinter().printFile(ts.factory.updateSourceFile(source, statements));
  const compiled = ts.transpileModule(code, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const context = { exports: {}, ...bindings };
  vm.runInNewContext(compiled, context, { timeout: 2000, filename: file });
  return context.exports;
}
const reads = metadata("lib/assistant/mcp-api.ts", ["READ_TOOL_NAMES", "READ_TOOL_SCHEMAS", "READ_TOOL_DESCRIPTIONS"], tools);
const registry = metadata("lib/mcp/dispatch.ts", ["objectSchema", "id", "RESULT_SCHEMA", "extras", "manifest"], { ...reads, writeTools: tools.mcpWriteTools, capabilityAllows });
const entries = registry.manifest({ clientId: "documentation", userId: "documentation", capabilities: ALL_CAPABILITIES });
const escape = value => String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
const body = [
  "# Generated MCP capabilities", "",
  "Generated by `node scripts/generate-mcp-docs.mjs` from the application registry. Do not edit manually.", "",
  `The full-access manifest has **${entries.length} tools** (${entries.filter(t => t.read_only).length} read-only, ${entries.filter(t => !t.read_only).length} write/operation tools). Each connection sees only its permitted subset.`, "",
  "Every external send/invitation requires owner approval in the app. No MCP tool grants approval. Guest-bearing calendar edits/deletions are refused by the autonomous path. Private assistant transcripts and provider secrets are never exposed.", "",
  "## Permissions", "",
  "| Capability | Meaning |", "|---|---|",
  ...Object.entries(CAPABILITY_DESCRIPTIONS).map(([key, item]) => `| ${key} | ${escape(item.description)} |`), "",
  "Mailbox/work-stream restrictions are enforced conservatively: tools whose joins cannot honor a selection are unavailable. They do not return an unfiltered substitute.", "",
  "## Tools", "", "| Tool | Behavior | Description |", "|---|---|---|",
  ...entries.map(t => `| ${t.name} | ${t.read_only ? "Read" : t.queues_for_approval ? "Queue for owner approval" : "Write / operation"} | ${escape(t.description)} |`), "",
  "## Resources", "", ...listResources(entries.map(t => t.name)).map(r => `- \`${r.uri}\`: ${r.description}`), "",
  "## Prompts", "", ...listPrompts(entries.map(t => t.name)).map(p => `- \`${p.name}\`: ${p.description}`), "",
  "## Result and retry contract", "",
  "Tools return structured state and data alongside readable text. Writes accept `_idempotency_key`; reuse a key only for the identical operation. Keep the returned operation ID. Inspect uncertain/running operations before trying again. Provider outcomes cannot be made transactional with the app database.", "",
  "Versioned previews support the documented task/note text fields only. Each committed record and undo history entry is atomic; bounded bulk commits return per-item outcomes and may partially succeed. Jobs report real phases, not invented percentages. Cancellation never reverses completed effects.", "",
].join("\n");
const destination = path.join(root, "docs/generated/mcp-capabilities.md");
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, body);
fs.writeFileSync(path.join(root, "docs/generated/mcp-manifest.json"), JSON.stringify({ read_tools: entries.filter(t => t.read_only), write_tools: entries.filter(t => !t.read_only), resources: listResources(entries.map(t => t.name)), prompts: listPrompts(entries.map(t => t.name)) }, null, 2) + "\n");
console.log(`Generated ${path.relative(root, destination)} (${entries.length} tools).`);
